#!/bin/bash

# Script to generate JWT tokens for all users in the database
# Queries the database for all user IDs and generates a JWT token for each
# Output is a JavaScript object mapping user IDs to JWT tokens

set -e

# Change to backend directory to access .env file
cd "$(dirname "$0")/.."

# Load environment variables from .env if it exists
if [ -f .env ]; then
  export $(grep -v '^#' .env | xargs)
fi

# Check if DATABASE_URL is set
if [ -z "$DATABASE_URL" ]; then
  echo "ERROR: DATABASE_URL environment variable is not set"
  echo "Please set DATABASE_URL or create a .env file in the backend directory"
  exit 1
fi

OUTPUT_FILE="loadtest/all_user_tokens.js"

echo "Fetching all user IDs from database..."

# Query database for all user IDs
USER_IDS=$(psql "$DATABASE_URL" -t -c "SELECT id FROM users ORDER BY id;")

# Convert to array
USER_ID_ARRAY=()
while IFS= read -r line; do
  # Trim whitespace
  trimmed=$(echo "$line" | xargs)
  if [ -n "$trimmed" ]; then
    USER_ID_ARRAY+=("$trimmed")
  fi
done <<< "$USER_IDS"

USER_COUNT=${#USER_ID_ARRAY[@]}

if [ $USER_COUNT -eq 0 ]; then
  echo "ERROR: No users found in database"
  exit 1
fi

echo "Found $USER_COUNT users in database"
echo "Generating JWT tokens..."
echo ""

# Start the JavaScript file
cat > "$OUTPUT_FILE" << 'EOF'
// Auto-generated JWT tokens for load testing
// Generated by generate_all_tokens.sh from all database users

export const tokensByUserID = {
EOF

# Generate tokens for each user
PROGRESS=0
for USER_ID in "${USER_ID_ARRAY[@]}"; do
  PROGRESS=$((PROGRESS + 1))
  echo "[$PROGRESS/$USER_COUNT] Generating token for $USER_ID..."

  TOKEN=$(go run cmd/gentoken/main.go "$USER_ID")

  if [ $? -eq 0 ]; then
    echo "  '$USER_ID': '$TOKEN'," >> "$OUTPUT_FILE"
  else
    echo "ERROR: Failed to generate token for $USER_ID"
    exit 1
  fi
done

# Close the JavaScript object
echo "};" >> "$OUTPUT_FILE"

# Also export the user IDs as an array for convenience
echo "" >> "$OUTPUT_FILE"
echo "// Array of all user IDs for easy random selection" >> "$OUTPUT_FILE"
echo "export const allUserIDs = Object.keys(tokensByUserID);" >> "$OUTPUT_FILE"

echo ""
echo "Successfully generated tokens for $USER_COUNT users"
echo "Output written to: $OUTPUT_FILE"
echo ""
echo "To use in k6 tests:"
echo "  import { tokensByUserID, allUserIDs } from './all_user_tokens.js';"
